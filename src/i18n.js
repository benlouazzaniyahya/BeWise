const has = (obj, key) => Object.prototype.hasOwnProperty.call(obj, key);

function lookup(obj, path) {
  if (obj && has(obj, path)) return obj[path];
  let cur = obj;
  const parts = path.split('.');
  for (let i = 0; i < parts.length; i++) {
    const rest = parts.slice(i).join('.');
    if (cur && typeof cur === 'object' && has(cur, rest)) return cur[rest];
    if (cur === null || typeof cur !== 'object' || !has(cur, parts[i])) return undefined;
    cur = cur[parts[i]];
  }
  return cur;
}

function interpolate(text, vars) {
  if (!vars) return text;
  return String(text).replace(/\{(\w+)\}/g, (m, name) => (has(vars, name) ? vars[name] : m));
}

function translate(lang, key, vars) {
  const langStrings = STRINGS[lang] || {};
  let out = lookup(langStrings, key);
  if (out === undefined) out = lookup(STRINGS.en, key);
  if (out === undefined) return key;
  return interpolate(out, vars);
}

function tFor(lang) {
  return (key, vars) => translate(lang, key, vars);
}

function subjectLabel(lang, name) {
  const map = { arabic: 'subject.arabic', french: 'subject.french', english: 'subject.english', math: 'subject.math' };
  return translate(lang, map[name] || 'subject.english', undefined);
}

